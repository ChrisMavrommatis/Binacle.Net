	// Flat array is six values per item: Length, Width, Height, X, Y, Z.
	private static void Add(string name, int widthBits, ushort binLength, ushort binWidth,
		ushort binHeight, string sourceToken, ushort[] flat)
	{
		var items = new Item<ushort>[flat.Length / 6];
		for (var index = 0; index < items.Length; index++)
		{
			var offset = index * 6;
			items[index] = new Item<ushort>
			{
				Length = flat[offset], Width = flat[offset + 1], Height = flat[offset + 2],
				X = flat[offset + 3], Y = flat[offset + 4], Z = flat[offset + 5]
			};
		}

		samples.Add(name, new PackingSample
		{
			Name = name,
			WidthBits = widthBits,
			Spread = "real",
			Bin = new Dimensions<ushort> { Length = binLength, Width = binWidth, Height = binHeight },
			Items = items,
			SourceToken = sourceToken
		});
	}

